CREATE EXTENSION IF NOT EXISTS pgcrypto;   /* crypt() / gen_salt() para las contrasenas */


/******************************************************************************/
/****                       Usuarios y permisos                            ****/
/****  En AW la contrasena esta en texto plano y PERMISOS_USUARIOS tiene   ****/
/****  una columna CHAR(1) por permiso. Aqui la contrasena va como hash    ****/
/****  bcrypt (password_verify() de PHP la valida) y cada permiso es un    ****/
/****  renglon, con los mismos nombres que usa exigirPermiso().            ****/
/******************************************************************************/

CREATE TABLE usuarios (
    usuario_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    login             VARCHAR(50) NOT NULL,
    contrasena_hash   VARCHAR(100) NOT NULL,   /* crypt('clave', gen_salt('bf')) o password_hash() de PHP */
    nombre            VARCHAR(150),
    correo            VARCHAR(150),
    estatus           CHAR(1) NOT NULL DEFAULT 'A',   /* A activo · B baja (como en AW) */
    id_hubspot        VARCHAR(30),
    fecha_creacion    TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultimo_acceso     TIMESTAMPTZ,
    CONSTRAINT pk_usuarios PRIMARY KEY (usuario_id),
    CONSTRAINT ck_usuarios_estatus CHECK (estatus IN ('A', 'B'))
);

/* El login se busca con upper(trim()) igual que en login.php */
CREATE UNIQUE INDEX uq_usuarios_login ON usuarios (upper(trim(login)));

CREATE TABLE permisos_usuarios (
    usuario_id  INTEGER NOT NULL,
    permiso     VARCHAR(60) NOT NULL,          /* MODULO_SUGERIDOS_OBRA, NUEVO_OBRA, ADMIN_USER... */
    CONSTRAINT pk_permisos_usuarios PRIMARY KEY (usuario_id, permiso),
    CONSTRAINT fk_permisos_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (usuario_id) ON DELETE CASCADE
);


