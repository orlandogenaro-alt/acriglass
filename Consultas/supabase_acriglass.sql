/* Borra un concepto del catalogo solo si ningun presupuesto lo usa.
   TIPO: 1 materia prima, 2 mano de obra, 3 gastos de operacion
   Uso: CALL elimina_concepto_obra(123, 1); */
CREATE PROCEDURE elimina_concepto_obra(p_concepto_id INTEGER, p_tipo INTEGER)
LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM doctos_sugerido_obra_det t WHERE t.concepto_id = p_concepto_id) THEN
    RAISE EXCEPTION 'EL CONCEPTO QUE INTENTA ELIMINAR YA SE ENCUENTRA RELACIONADO EN UN PRESUPUESTO, NO ES POSIBLE ELIMINAR';
  END IF;

  IF p_tipo = 1 THEN
    DELETE FROM conceptos_mat_prima_obra WHERE concepto_mat_prima_id = p_concepto_id;
  ELSIF p_tipo = 2 THEN
    DELETE FROM conceptos_mano_obra WHERE concepto_mano_obra_id = p_concepto_id;
  ELSIF p_tipo = 3 THEN
    DELETE FROM conceptos_gas_operacion_obra WHERE concepto_gas_operacion_obra_id = p_concepto_id;
  END IF;
END $$;


