/****      archivos (los .json de config, uploads, sesiones de PHP), porque ****/
/****      en Vercel el disco es de solo lectura y se borra en cada         ****/
/****      despliegue.                                                      ****/
/****                                                                       ****/
/****  Las tablas y columnas de obras conservan los nombres de AW para que  ****/
/****  las consultas de api/obras.php sirvan casi sin cambios y los datos   ****/
/****  se puedan pasar 1 a 1. Nombres sin comillas = minusculas, igual que  ****/
/****  las llaves que regresa bd_filas() (PDO::CASE_LOWER).                ****/
/****                                                                       ****/
/****  Como correrlo: Supabase > SQL Editor > New query > pegar todo > Run  ****/
/****  Se corre una sola vez en un proyecto vacio.                          ****/
