/* Fecha de actualizacion del parametro al darlo de alta o cambiar su valor */
CREATE FUNCTION parametros_costos_fecha() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.valor IS DISTINCT FROM OLD.valor THEN
    NEW.fecha_actualizacion := CURRENT_DATE;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER parametros_costos_biu BEFORE INSERT OR UPDATE ON parametros_costos_sug
  FOR EACH ROW EXECUTE FUNCTION parametros_costos_fecha();

CREATE FUNCTION configuracion_fecha() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.actualizado := now();
  RETURN NEW;
END $$;

CREATE TRIGGER configuracion_bu BEFORE UPDATE ON configuracion
  FOR EACH ROW EXECUTE FUNCTION configuracion_fecha();


