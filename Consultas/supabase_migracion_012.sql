        DROP TRIGGER IF EXISTS auditoria_pago_comis_por_obra_enca ON pago_comis_por_obra_enca;
        CREATE TRIGGER auditoria_pago_comis_por_obra_enca AFTER INSERT OR UPDATE OR DELETE ON pago_comis_por_obra_enca
            FOR EACH ROW EXECUTE FUNCTION auditoria_registrar('pago_comis_por_obra_enca_id');
        DROP TRIGGER IF EXISTS auditoria_pago_comis_por_obra ON pago_comis_por_obra;
        CREATE TRIGGER auditoria_pago_comis_por_obra AFTER INSERT OR UPDATE OR DELETE ON pago_comis_por_obra
