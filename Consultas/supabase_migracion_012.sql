/****  pago_comis_por_obra_enca /   6-Mano de Obra › Comisiones: cálculo de ****/
/****  pago_comis_por_obra:         comisiones de administrativos (tipo 1)  ****/
/****                               u operativos (tipo 2) por empleado.     ****/
/****                                                                       ****/
/****  Se aplica con: php herramientas/migrar.php --aplicar                 ****/
/******************************************************************************/

CREATE TABLE IF NOT EXISTS documentos_relac_obras (
    docto_relac_obra_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id              INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    tipo_docto           VARCHAR(2) NOT NULL DEFAULT 'PV',
    docto_id             INTEGER,
    folio                VARCHAR(20) NOT NULL,
    unidades             NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (unidades >= 0),
    importe              NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (importe >= 0),
    fecha_creacion       TIMESTAMPTZ NOT NULL DEFAULT now(),
    usuario_creacion     VARCHAR(50)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_documentos_relac_obras ON documentos_relac_obras (obra_id, tipo_docto, upper(trim(folio)));

CREATE TABLE IF NOT EXISTS gastos_oper_adic_obra (
    gasto_oper_adic_obra_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id                         INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    concepto_gas_operacion_obra_id  INTEGER NOT NULL,
    concepto                        VARCHAR(80),
    porcentaje                      NUMERIC(15,4) NOT NULL DEFAULT 0 CHECK (porcentaje >= 0 AND porcentaje <= 100),
    CONSTRAINT uq_gastos_oper_adic_obra UNIQUE (obra_id, concepto_gas_operacion_obra_id)
);

CREATE TABLE IF NOT EXISTS pago_comis_por_obra_enca (
    pago_comis_por_obra_enca_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id                      INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    fecha                        DATE NOT NULL DEFAULT CURRENT_DATE,
    tipo_id                      INTEGER NOT NULL DEFAULT 2 CHECK (tipo_id IN (1, 2)),   /* 1 administrativos · 2 operativos */
    estatus                      VARCHAR(10) NOT NULL DEFAULT 'Normal' CHECK (estatus IN ('Normal', 'Cancelado')),
    importe_neto                 NUMERIC(15,2) NOT NULL DEFAULT 0,
    notas                        VARCHAR(200),
    fecha_creacion               TIMESTAMPTZ NOT NULL DEFAULT now(),
    usuario_creacion             VARCHAR(60)
);
CREATE INDEX IF NOT EXISTS ix_pago_comis_obra ON pago_comis_por_obra_enca (obra_id, fecha);

CREATE TABLE IF NOT EXISTS pago_comis_por_obra (
    pago_comis_por_obra_det      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_comis_por_obra_enca_id  INTEGER NOT NULL REFERENCES pago_comis_por_obra_enca (pago_comis_por_obra_enca_id) ON DELETE CASCADE,
    empleado_id                  INTEGER,
    nombre                       VARCHAR(150) NOT NULL,
    hrs_trabajadas               NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (hrs_trabajadas >= 0),
    por_comision                 NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (por_comision >= 0 AND por_comision <= 100),
    importe_pagar                NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (importe_pagar >= 0),
    descuentos                   NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (descuentos >= 0)
);
CREATE INDEX IF NOT EXISTS ix_pago_comis_det ON pago_comis_por_obra (pago_comis_por_obra_enca_id);

ALTER TABLE documentos_relac_obras   ENABLE ROW LEVEL SECURITY;
ALTER TABLE gastos_oper_adic_obra    ENABLE ROW LEVEL SECURITY;
ALTER TABLE pago_comis_por_obra_enca ENABLE ROW LEVEL SECURITY;
ALTER TABLE pago_comis_por_obra      ENABLE ROW LEVEL SECURITY;

