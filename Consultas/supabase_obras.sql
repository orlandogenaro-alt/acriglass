CREATE INDEX IF NOT EXISTS ix_doctos_adic_cobro_obra   ON doctos_adic_cobro_obra (obra_id);
CREATE INDEX IF NOT EXISTS ix_doctos_orden_obra        ON doctos_orden_obra (obra_id);
CREATE INDEX IF NOT EXISTS ix_explocion_material_obra  ON explocion_material_de_obra (obra_id);
CREATE INDEX IF NOT EXISTS ix_solicitudes_orden        ON dvd_solicitudes_material (docto_orden_obra_id);
CREATE INDEX IF NOT EXISTS ix_empleados_asig_obra      ON empleados_asignados_a_obra (obra_id);
CREATE INDEX IF NOT EXISTS ix_bitacora_mov_sis_costos  ON bitacora_movimientos_sis_costos (id_optimizacion);
CREATE INDEX IF NOT EXISTS ix_consumos_obra            ON consumos_metrial_en_obra (obra_id);
CREATE INDEX IF NOT EXISTS ix_gastos_adic_obra         ON gastos_adicionales_obra (obra_id);
CREATE INDEX IF NOT EXISTS ix_archivos_adjuntos        ON archivos_adjuntos (suerido_id);
CREATE INDEX IF NOT EXISTS ix_conceptos_tareas         ON conceptos_tareas (docto_sugerido_obra_id, orden);

/* Conceptos de gasto iniciales (en el diálogo de gasto se pueden escribir otros) */
