/* Folios: GEN_COT_OBRA (ordenes de trabajo) y DVD_FOLIO_MOV_ADIC_OBRA (documentos de cobro) de AW */
CREATE SEQUENCE IF NOT EXISTS folios_cot_obra;
CREATE SEQUENCE IF NOT EXISTS folio_mov_adic_obra;

/* ---------- 2-Facturacion ---------- */

/* Cotizaciones / pedidos de Microsip asignados a la obra */
CREATE TABLE IF NOT EXISTS doctos_microsip_obra (
    docto_orden_obra_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id               INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    cliente_id            INTEGER,
    clave_cliente         VARCHAR(30),
    nom_cliente           VARCHAR(200),
    folio                 VARCHAR(9),
    fecha                 DATE,
    fecha_entrega         DATE,
    estatus               CHAR(1),
    descripcion           VARCHAR(200),
    importe_neto          NUMERIC(15,2) DEFAULT 0,
    fecha_creacion        TIMESTAMPTZ DEFAULT now(),
    fecha_mod             TIMESTAMPTZ,
    usuario_creacion      VARCHAR(50),
    usuario_modificacion  VARCHAR(50)
);

/* Partidas de la Cotizacion Microsip (pestaña General) */
CREATE TABLE IF NOT EXISTS doctos_microsip_obra_det (
    docto_orden_obra_det_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docto_orden_obra_id      INTEGER NOT NULL REFERENCES doctos_microsip_obra (docto_orden_obra_id) ON DELETE CASCADE,
    articulo_id              INTEGER,
    clave_articulo           VARCHAR(30),
    descripcion              VARCHAR(200),
    unidades                 NUMERIC(15,2) DEFAULT 0,
    um                       VARCHAR(30),
    precio_unitario          NUMERIC(15,2) DEFAULT 0,
    precio_total             NUMERIC(15,2) DEFAULT 0,
    notas_adic               TEXT,
    pos                      INTEGER,
    costo_unit               NUMERIC(15,2) DEFAULT 0
);
/* Urgencia de la cotización (solo en la base en línea; en AW no existe la columna) */
ALTER TABLE doctos_microsip_obra ADD COLUMN IF NOT EXISTS urgencia VARCHAR(30);

/* Pago en efectivo (0), nota de cargo (1) y anticipo (2) */
CREATE TABLE IF NOT EXISTS doctos_adic_cobro_obra (
    docto_adic_cobro_obra_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id                   INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    tipo                      INTEGER,
    es_microsip               CHAR(10),
    docto_id_microsip         INTEGER,
    concepto_cc_id            INTEGER,
    folio                     VARCHAR(10),
    importe                   NUMERIC(15,2) DEFAULT 0,
    notas                     VARCHAR(200),
    fecha                     DATE,
    fecha_creacion            TIMESTAMPTZ DEFAULT now(),
    usuario_creacion          VARCHAR(50),
    estatus                   VARCHAR(15)
);

/* ---------- 3-Orden de trabajo ---------- */
/* estatus: O = por liberar, P = en produccion, F = fin de produccion, C = cancelada */
CREATE TABLE IF NOT EXISTS doctos_orden_obra (
    docto_orden_obra_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id               INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    cliente_id            INTEGER,
    clave_cliente         VARCHAR(30),
    nom_cliente           VARCHAR(200),
    folio                 VARCHAR(9),
    fecha                 DATE,
    fecha_entrega         DATE,
    estatus               CHAR(1) DEFAULT 'O',
    descripcion           VARCHAR(200),
    importe_neto          NUMERIC(15,2) DEFAULT 0,
    fecha_creacion        TIMESTAMPTZ DEFAULT now(),
    fecha_mod             TIMESTAMPTZ,
    usuario_creacion      VARCHAR(50),
    usuario_modificacion  VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS doctos_orden_obra_det (
    docto_orden_obra_det_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docto_orden_obra_id      INTEGER NOT NULL REFERENCES doctos_orden_obra (docto_orden_obra_id) ON DELETE CASCADE,
    articulo_id              INTEGER,
    clave_articulo           VARCHAR(30),
    descripcion              VARCHAR(200),
    unidades                 NUMERIC(15,2) DEFAULT 0,
    um                       VARCHAR(30),
    precio_unitario          NUMERIC(15,2) DEFAULT 0,
    precio_total             NUMERIC(15,2) DEFAULT 0,
    notas_adic               TEXT,
    pos                      INTEGER
);

/* ---------- 4-Explosion de material ---------- */
CREATE TABLE IF NOT EXISTS explocion_material_de_obra (
    explocion_mat_obra_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id                INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    articulo_id            INTEGER,
    clave                  VARCHAR(30),
    nombre                 VARCHAR(200),
    um                     VARCHAR(15),
    uds                    NUMERIC(15,3) DEFAULT 0,
    costo_unit             NUMERIC(15,2) DEFAULT 0,
    costo_tot              NUMERIC(15,2) DEFAULT 0,
    uni_med_ml_mq          VARCHAR(15),
    tipo_docto             VARCHAR(30),
    folio                  VARCHAR(20)
);

/* ---------- 5-Salidas de material (solicitudes de las ordenes de trabajo) ---------- */
CREATE TABLE IF NOT EXISTS dvd_solicitudes_material (
    docto_solicitud_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto_in_id        INTEGER,
    almacen_id_org        INTEGER,
    almacen_id_dest       INTEGER,
    fecha                 DATE,
    descripcion           VARCHAR(400),
    usuario_creador       VARCHAR(50),
    usuario_modificacion  VARCHAR(50),
    fecha_creacion        TIMESTAMPTZ DEFAULT now(),
    estatus               VARCHAR(20) DEFAULT 'Pendiente',
    nom_almacen           VARCHAR(60),
    nom_concepto          VARCHAR(60),
    docto_in_id           INTEGER,
    folio_microsip        VARCHAR(10),
    nom_empresa           VARCHAR(100),
    tipo_mov              INTEGER,
    docto_orden_obra_id   INTEGER REFERENCES doctos_orden_obra (docto_orden_obra_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS doctos_solicitudes_det (
    docto_solicitud_id_det  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docto_solicitud_id      INTEGER NOT NULL REFERENCES dvd_solicitudes_material (docto_solicitud_id) ON DELETE CASCADE,
    almacen_id              INTEGER,
    articulo_id             INTEGER,
    clave_art               VARCHAR(30),
    nom_art                 VARCHAR(200),
    unid_med                VARCHAR(30),
    unidades                NUMERIC(15,3) DEFAULT 0,
    costo_unitario          NUMERIC(15,2) DEFAULT 0,
    costo_total             NUMERIC(15,2) DEFAULT 0
);

/* ---------- 6-Mano de obra ---------- */
CREATE TABLE IF NOT EXISTS empleados_asignados_a_obra (
    empleado_asignado_obra_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id                    INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    docto_orden_obra_id        INTEGER,
    unidad_transporte_id       INTEGER,
    nom_unidad                 VARCHAR(100),
    estatus                    CHAR(1) DEFAULT 'A',
    fecha                      DATE,
    importe_mo                 NUMERIC(15,2) DEFAULT 0,
    imp_mo_real                NUMERIC(15,2) DEFAULT 0,
    notas                      VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS empleados_asignados_a_obra_det (
    empleado_asignado_a_obra_det_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_asignado_obra_id        INTEGER NOT NULL REFERENCES empleados_asignados_a_obra (empleado_asignado_obra_id) ON DELETE CASCADE,
    id_empleado                      INTEGER,
    nombre                           VARCHAR(150),
    costo_x_hrs                      NUMERIC(15,2) DEFAULT 0,
    hrs_trabajo                      NUMERIC(15,2) DEFAULT 0,
    hrs_trabajo_real                 NUMERIC(15,2) DEFAULT 0,
    costo_tot_pres                   NUMERIC(15,2) DEFAULT 0,
    cost_tot_real                    NUMERIC(15,2) DEFAULT 0
);

/* Bitácora de los documentos (guarda_bitacora_costos_prod / consulta_bitacora_mov_t de AW) */
CREATE TABLE IF NOT EXISTS bitacora_movimientos_sis_costos (
    id_optimizacion   INTEGER,
    num_optimizacion  INTEGER,
    usuario           VARCHAR(50),
    fecha_hora        TIMESTAMP,
    notas             VARCHAR(100)
);

/* ---------- 7-Consumos ---------- */
CREATE TABLE IF NOT EXISTS consumos_metrial_en_obra (
    consumo_material_obra_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obra_id                   INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    fecha                     DATE,
    folio                     INTEGER,
    estatus                   VARCHAR(15),
    equipo_trans_id           INTEGER,
    docto_orden_obra_id       INTEGER,
    descripcion               VARCHAR(250),
    fecha_creacion            TIMESTAMPTZ DEFAULT now(),
    usuario_creacion          VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS consumos_material_en_obra_det (
    consumo_material_obra_det_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumo_meterial_obra_id      INTEGER NOT NULL REFERENCES consumos_metrial_en_obra (consumo_material_obra_id) ON DELETE CASCADE,
    articulo_id                   INTEGER,
    clave                         VARCHAR(30),
    descripcion                   VARCHAR(200),
    uds_consumo                   NUMERIC(15,3) DEFAULT 0,
    unimed                        VARCHAR(30)
);

/* Personal que participa en un gasto adicional (Dialog274.grid_responsables) */
CREATE TABLE IF NOT EXISTS personal_consumo_en_obra (
    personal_consumo_obra_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumo_material_obra_id  INTEGER NOT NULL,
    id_empleado               INTEGER,
    nombre_empleado           VARCHAR(150)
);

/* ---------- 8-Gastos adicionales ---------- */
CREATE TABLE IF NOT EXISTS conceptos_gastos_obra (
    concepto_gasto_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(60),
    tipo               INTEGER
);

CREATE TABLE IF NOT EXISTS unidades_transporte (
    unidad_trans_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave               VARCHAR(30),
    nombre              VARCHAR(100),
    precio_gasolina_id  NUMERIC(15,2),
    rendimiento         NUMERIC(15,4),
    modelo              VARCHAR(50),
    estatus             VARCHAR(20),
    depresiacion_x_dia  NUMERIC(15,2),
    capacidad_carga     NUMERIC(15,2),
    equipo_trans_id     INTEGER
);

/* estatus: A = activo, C = cancelado */
CREATE TABLE IF NOT EXISTS gastos_adicionales_obra (
    gasto_adicional_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto_gasto_id     INTEGER,
    obra_id               INTEGER NOT NULL REFERENCES reg_obras (obra_id) ON DELETE CASCADE,
    docto_orden_obra_id   INTEGER,
    unidad_transporte_id  INTEGER,
    nom_unidad            VARCHAR(100),
    importe               NUMERIC(15,2) DEFAULT 0,
    notas                 VARCHAR(300),
    fecha_creacion        TIMESTAMPTZ DEFAULT now(),
    estatus               CHAR(1) DEFAULT 'A'
);

CREATE TABLE IF NOT EXISTS gastos_adicionales_obra_det (
    gasto_adicional_obra_det_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gasto_adicional_id           INTEGER NOT NULL REFERENCES gastos_adicionales_obra (gasto_adicional_id) ON DELETE CASCADE,
    concepto_gasto_id            INTEGER,
    imp_presupuestado            NUMERIC(15,2) DEFAULT 0,
    imp_real                     NUMERIC(15,2) DEFAULT 0
);

/* ---------- 9-Adjuntos ---------- */
CREATE TABLE IF NOT EXISTS archivos_adjuntos (
    archivo_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_archivo     VARCHAR(150),
    tamano             INTEGER,
    fecha_creacion     TIMESTAMPTZ DEFAULT now(),
    usuario_creacion   VARCHAR(50),
    archivo_adjunto    BYTEA,
    suerido_id         INTEGER,
    descripcion_corta  CHAR(50)
);

/* ---------- 13-Conceptos/Tareas (los comparten el presupuesto y la obra) ---------- */
/* uid / padre_uid: árbol dentro del presupuesto · origen: concepto de MP/MO/GO ('mp:3', partida 'mp:3:0')
   tipo: Concepto, Tarea, Hito o Excluido (concepto quitado de la lista) · avance 0-100 · estatus: Pendiente,
   En proceso, Terminada o Atrasada · manual: campos capturados a mano que ya no se generan solos */
CREATE TABLE IF NOT EXISTS conceptos_tareas (
    tarea_id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docto_sugerido_obra_id  INTEGER NOT NULL REFERENCES doctos_sugerido_obra (docto_sugerido_obra_id) ON DELETE CASCADE,
    uid                     INTEGER NOT NULL,
    padre_uid               INTEGER,
    orden                   INTEGER,
    origen                  VARCHAR(30),
    tipo                    VARCHAR(15),
    clave                   VARCHAR(30),
    nombre                  VARCHAR(200),
    agrupador               VARCHAR(100),
    descripcion             TEXT,
    cantidad                NUMERIC(15,3) DEFAULT 0,
    unidad                  VARCHAR(30),
    monto                   NUMERIC(15,2) DEFAULT 0,
    ini_real                TIMESTAMP,
    fin_real                TIMESTAMP,
    ini_cli                 TIMESTAMP,
    fin_cli                 TIMESTAMP,
    jornada                 VARCHAR(50),
    responsable             VARCHAR(150),
    empleados               VARCHAR(500),
    color                   VARCHAR(10),
    avance                  NUMERIC(5,2) DEFAULT 0,
    estatus                 VARCHAR(20),
    manual                  VARCHAR(100),
    fecha_mod               TIMESTAMPTZ DEFAULT now(),
    usuario_mod             VARCHAR(50)
);

CREATE INDEX IF NOT EXISTS ix_doctos_microsip_obra     ON doctos_microsip_obra (obra_id);
