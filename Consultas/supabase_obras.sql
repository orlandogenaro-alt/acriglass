SELECT v.nombre, 0 FROM (VALUES ('COMBUSTIBLE'), ('CASETAS'), ('HOSPEDAJE'), ('COMIDAS'), ('VIATICOS'), ('FLETES'), ('MATERIAL DIVERSO'), ('HERRAMIENTA')) AS v(nombre)
WHERE NOT EXISTS (SELECT 1 FROM conceptos_gastos_obra);

