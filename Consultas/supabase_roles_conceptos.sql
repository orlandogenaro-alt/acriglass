/******************************************************************************/
/****                               Roles                                  ****/
/******************************************************************************/

CREATE TABLE IF NOT EXISTS roles (
    rol_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(60) NOT NULL,
    descripcion  VARCHAR(200),
    CONSTRAINT pk_roles PRIMARY KEY (rol_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_roles_nombre ON roles (upper(trim(nombre)));

CREATE TABLE IF NOT EXISTS permisos_roles (
    rol_id   INTEGER NOT NULL,
    permiso  VARCHAR(60) NOT NULL,          /* mismos nombres que permisos_usuarios */
    CONSTRAINT pk_permisos_roles PRIMARY KEY (rol_id, permiso),
    CONSTRAINT fk_permisos_rol FOREIGN KEY (rol_id)
        REFERENCES roles (rol_id) ON DELETE CASCADE
);

ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS rol_id INTEGER;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuarios_rol') THEN
    ALTER TABLE usuarios ADD CONSTRAINT fk_usuarios_rol FOREIGN KEY (rol_id)
      REFERENCES roles (rol_id) ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_usuarios_rol ON usuarios (rol_id);

ALTER TABLE roles           ENABLE ROW LEVEL SECURITY;
ALTER TABLE permisos_roles  ENABLE ROW LEVEL SECURITY;

/* Roles de inicio (el administrador los puede cambiar en Administrador > Roles) */
INSERT INTO roles (nombre, descripcion)
SELECT v.nombre, v.descripcion
  FROM (VALUES
    ('ADMINISTRADOR', 'Acceso a todo el sistema, incluido el menu Administrador'),
    ('PRESUPUESTOS',  'Captura y modifica presupuestos de obra'),
    ('OBRAS',         'Registra, modifica y cierra obras'),
    ('CONSULTA',      'Solo consulta presupuestos y obras')
  ) AS v (nombre, descripcion)
 WHERE NOT EXISTS (SELECT 1 FROM roles r WHERE upper(trim(r.nombre)) = v.nombre);

INSERT INTO permisos_roles (rol_id, permiso)
SELECT r.rol_id, v.permiso
  FROM (VALUES
    ('ADMINISTRADOR', 'ADMIN_USER'),
    ('PRESUPUESTOS',  'MODULO_SUGERIDOS_OBRA'),
    ('PRESUPUESTOS',  'NUEVO_SUGERIDO_OBRA'),
    ('PRESUPUESTOS',  'MODIFICAR_SUGERIDO_OBRA'),
    ('OBRAS',         'MODULO_SUGERIDOS_OBRA'),
    ('OBRAS',         'NUEVO_OBRA'),
    ('OBRAS',         'MODIFICAR_OBRA'),
    ('OBRAS',         'CERRAR_OBRA'),
    ('CONSULTA',      'MODULO_SUGERIDOS_OBRA')
  ) AS v (rol, permiso)
  JOIN roles r ON upper(trim(r.nombre)) = v.rol
ON CONFLICT (rol_id, permiso) DO NOTHING;


