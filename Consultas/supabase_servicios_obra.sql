CREATE TABLE IF NOT EXISTS servicios_obra (
    servicio_obra_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo            VARCHAR(20) NOT NULL,
    obra_id           INTEGER,            /* vacio = gasto general (cuentas por pagar e indirectos) */
    fecha             DATE,
    fecha_fin         DATE,
    fecha_vence       DATE,
    folio             VARCHAR(30),
    concepto          VARCHAR(200),
    tipo              VARCHAR(60),
    proveedor         VARCHAR(150),
    responsable       VARCHAR(150),
    cantidad          NUMERIC(15,3) DEFAULT 0,
    unidad            VARCHAR(30),
    precio            NUMERIC(15,2) DEFAULT 0,
    importe           NUMERIC(15,2) DEFAULT 0,
    pagado            NUMERIC(15,2) DEFAULT 0,
    avance            NUMERIC(5,2) DEFAULT 0,
    estatus           VARCHAR(30),
    revision          VARCHAR(20),
    notas             VARCHAR(2000),
    nombre_archivo    VARCHAR(150),
    archivo           BYTEA,
    fecha_creacion    TIMESTAMP DEFAULT now(),
    usuario_creacion  VARCHAR(50),
    fecha_mod         TIMESTAMP,
    usuario_mod       VARCHAR(50)
);

CREATE INDEX IF NOT EXISTS ix_servicios_obra_obra  ON servicios_obra (modulo, obra_id);
CREATE INDEX IF NOT EXISTS ix_servicios_obra_fecha ON servicios_obra (modulo, fecha);

/* Igual que las demás tablas: solo el servidor (service_role / usuario de la conexión) la usa */
ALTER TABLE servicios_obra ENABLE ROW LEVEL SECURITY;
