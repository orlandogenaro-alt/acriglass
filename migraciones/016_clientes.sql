/* ---------- Catálogos de la ficha ---------- */
CREATE TABLE IF NOT EXISTS condiciones_pago (
    cond_pago_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE,
    dias_credito     INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tipos_clientes (
    tipo_cliente_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tipos_moneda (
    moneda_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE,
    clave            VARCHAR(5),
    simbolo          VARCHAR(5) DEFAULT '$'
);

CREATE TABLE IF NOT EXISTS zonas_clientes (
    zona_cliente_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS sistema_dimenciones (
    sistema_dim_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE,
    udm              VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS ciudades (
    ciudad_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE,
    estado           VARCHAR(60)
);

/* ---------- Clientes ---------- */
CREATE SEQUENCE IF NOT EXISTS clave_clientes_consec;   /* clave visible del cliente */

CREATE TABLE IF NOT EXISTS clientes (
    cliente_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_cliente      VARCHAR(20) NOT NULL UNIQUE,
    nombre             VARCHAR(200) NOT NULL,          /* Empresa (en mayúsculas) */
    contacto           VARCHAR(200),
    telefono           VARCHAR(35),
    email              VARCHAR(200),
    rfc                VARCHAR(18),
    cond_pago_id       INTEGER REFERENCES condiciones_pago (cond_pago_id),
    tipo_cliente_id    INTEGER REFERENCES tipos_clientes (tipo_cliente_id),
    moneda_id          INTEGER REFERENCES tipos_moneda (moneda_id),
    zona_cliente_id    INTEGER REFERENCES zonas_clientes (zona_cliente_id),
    sistema_dim_id     INTEGER REFERENCES sistema_dimenciones (sistema_dim_id),
    vendedor_id        INTEGER REFERENCES vendedores_obras (vendedor_obra_id),
    vendedor_campo_id  INTEGER REFERENCES vendedores_obras (vendedor_obra_id),
    direccion          TEXT,
    referencia         VARCHAR(100),
    ciudad_id          INTEGER REFERENCES ciudades (ciudad_id),
    codigo_postal      VARCHAR(10),
    condiciones_com    TEXT,
    impuesto           INTEGER DEFAULT 0,
    total_impuesto     NUMERIC(5,2) DEFAULT 0,
    estatus            CHAR(1) DEFAULT 'A',
    fecha_creacion     TIMESTAMPTZ DEFAULT now(),
    usuario_creador    VARCHAR(50)
);
CREATE UNIQUE INDEX IF NOT EXISTS clientes_nombre_unico ON clientes (upper(trim(nombre)));

/* Contactos de HubSpot relacionados con el cliente (estatus 0 = relación quitada) */
CREATE TABLE IF NOT EXISTS hs_clientes (
    id_rel_clientes  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_easy          INTEGER NOT NULL REFERENCES clientes (cliente_id) ON DELETE CASCADE,
    id_hubspot       VARCHAR(30) NOT NULL,
    hs_nombre        VARCHAR(200),
    hs_correo        VARCHAR(200),
    hs_telefono      VARCHAR(50),
    estatus          INTEGER DEFAULT 1,
    fecha            TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hs_clientes_cliente ON hs_clientes (id_easy) WHERE estatus = 1;

