/******************************************************************************/
/****  017 - Conceptos del Análisis P.U. del presupuesto en tablas          ****/
/****                                                                       ****/
/****  Hasta ahora los conceptos analizados de cada presupuesto y sus       ****/
/****  insumos vivían solo en el JSON doctos_sugerido_obra.analisis_pu.     ****/
/****  Aquí pasan a renglones con su propio id (el doble clic abre el       ****/
/****  concepto por ese id) y con los campos del motor de cálculo           ****/
/****  (includes/presupuesto-calculo.php): tipo de cálculo, rendimiento,    ****/
/****  factor, merma, base (unidad / fijo / % de la mano de obra), FSR      ****/
/****  propio, viáticos, proveedor, fecha de costo y la cantidad e importe  ****/
/****  resultantes por unidad del concepto.                                 ****/
/****  padre_id deja lista la matriz dentro de matriz (un insumo compuesto  ****/
/****  con sus componentes).                                                ****/
/****                                                                       ****/
/****  No borra nada: el JSON se sigue guardando como respaldo. Al final    ****/
/****  copia el JSON de los presupuestos ya guardados a las tablas (solo    ****/
/****  los que aún no tienen renglones, así que se puede volver a correr).  ****/
/****                                                                       ****/
/****  Se aplica con: php herramientas/migrar.php --aplicar                 ****/
/******************************************************************************/

CREATE TABLE IF NOT EXISTS presupuesto_conceptos (
    presupuesto_concepto_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docto_sugerido_obra_id   INTEGER NOT NULL REFERENCES doctos_sugerido_obra (docto_sugerido_obra_id) ON DELETE CASCADE,
    concepto_pu_id           INTEGER REFERENCES conceptos_pu (concepto_pu_id),   /* de qué concepto del catálogo salió */
    clave                    VARCHAR(20),
    partida                  VARCHAR(100),                     /* «Partida / Subpartida» */
    descripcion              VARCHAR(300),
    unidad                   VARCHAR(20),
    cantidad                 NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    venta                    NUMERIC(18,4),                     /* precio fijo para el cliente (importado del Catálogo) */
    especificacion           TEXT,
    orden                    INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_presupuesto_conceptos ON presupuesto_conceptos (docto_sugerido_obra_id, orden);

CREATE TABLE IF NOT EXISTS presupuesto_concepto_insumos (
    presupuesto_concepto_insumo_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_concepto_id         BIGINT NOT NULL REFERENCES presupuesto_conceptos (presupuesto_concepto_id) ON DELETE CASCADE,
    padre_id                        BIGINT REFERENCES presupuesto_concepto_insumos (presupuesto_concepto_insumo_id) ON DELETE CASCADE,
    insumo_id                       INTEGER REFERENCES insumos (insumo_id),     /* del catálogo, si salió de ahí */
    tipo                            VARCHAR(4) NOT NULL DEFAULT 'MAT' CHECK (tipo IN ('MAT', 'MO', 'EQ', 'MAQ', 'HER', 'OTRO')),
    codigo                          VARCHAR(30),
    descripcion                     VARCHAR(200),
    unidad                          VARCHAR(20),
    tipo_calculo                    VARCHAR(12) CHECK (tipo_calculo IS NULL OR tipo_calculo IN ('cantidad', 'rendimiento')),
    base                            VARCHAR(8) CHECK (base IS NULL OR base IN ('fijo', 'pct_mo')),   /* null = por unidad */
    cantidad                        NUMERIC(18,6) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    rinde                           NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (rinde >= 0),
    factor                          NUMERIC(18,6) CHECK (factor IS NULL OR factor >= 0),
    merma_pct                       NUMERIC(9,4) CHECK (merma_pct IS NULL OR merma_pct >= 0),
    costo                           NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (costo >= 0),   /* mano de obra: salario base */
    fsr                             NUMERIC(8,4) CHECK (fsr IS NULL OR fsr >= 0),          /* null = el del análisis */
    viaticos                        NUMERIC(18,4) CHECK (viaticos IS NULL OR viaticos >= 0),
    alimentacion                    NUMERIC(18,4) CHECK (alimentacion IS NULL OR alimentacion >= 0),
    hospedaje                       NUMERIC(18,4) CHECK (hospedaje IS NULL OR hospedaje >= 0),
    proveedor                       VARCHAR(150),
    fecha_costo                     DATE,
    cantidad_resultante             NUMERIC(18,6),     /* por unidad del concepto, la calcula el motor al guardar */
    importe                         NUMERIC(18,6),     /* por unidad del concepto, con FSR y viáticos */
    orden                           INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_presupuesto_concepto_insumos ON presupuesto_concepto_insumos (presupuesto_concepto_id, orden);
CREATE INDEX IF NOT EXISTS ix_presupuesto_concepto_insumos_padre ON presupuesto_concepto_insumos (padre_id);

ALTER TABLE presupuesto_conceptos        ENABLE ROW LEVEL SECURITY;
ALTER TABLE presupuesto_concepto_insumos ENABLE ROW LEVEL SECURITY;

/* Conversión: el JSON de los presupuestos ya guardados a las tablas (sin tocar el JSON) */
INSERT INTO presupuesto_conceptos (docto_sugerido_obra_id, clave, partida, descripcion, unidad, cantidad, venta, especificacion, orden)
SELECT d.docto_sugerido_obra_id,
       left(c->>'clave', 20), left(c->>'partida', 100), left(c->>'descripcion', 300), left(c->>'unidad', 20),
       greatest(coalesce((c->>'cantidad')::numeric, 0), 0), nullif((c->>'venta')::numeric, 0), c->>'especificacion', o.n
  FROM doctos_sugerido_obra d
 CROSS JOIN LATERAL jsonb_array_elements(coalesce(nullif(trim(d.analisis_pu), '')::jsonb->'conceptos', '[]'::jsonb)) WITH ORDINALITY AS o(c, n)
 WHERE d.analisis_pu IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM presupuesto_conceptos p WHERE p.docto_sugerido_obra_id = d.docto_sugerido_obra_id);

INSERT INTO presupuesto_concepto_insumos (presupuesto_concepto_id, tipo, codigo, descripcion, unidad, tipo_calculo, base,
                                          cantidad, rinde, factor, merma_pct, costo, fsr, viaticos, alimentacion, hospedaje,
                                          proveedor, fecha_costo, orden)
SELECT p.presupuesto_concepto_id,
       CASE WHEN i->>'tipo' IN ('MAT', 'MO', 'EQ', 'MAQ', 'HER', 'OTRO') THEN i->>'tipo' ELSE 'MAT' END,
       left(i->>'codigo', 30), left(i->>'descripcion', 200), left(i->>'unidad', 20),
       CASE WHEN i->>'tipo_calculo' IN ('cantidad', 'rendimiento') THEN i->>'tipo_calculo' END,
       CASE WHEN i->>'base' IN ('fijo', 'pct_mo') THEN i->>'base' END,
       greatest(coalesce((i->>'cantidad')::numeric, 0), 0), greatest(coalesce((i->>'rinde')::numeric, 0), 0),
       (i->>'factor')::numeric, (i->>'merma_pct')::numeric, greatest(coalesce((i->>'costo')::numeric, 0), 0),
       (i->>'fsr')::numeric, (i->>'viaticos')::numeric, (i->>'alimentacion')::numeric, (i->>'hospedaje')::numeric,
       left(i->>'proveedor', 150), (i->>'fecha_costo')::date, o2.n2
  FROM presupuesto_conceptos p
  JOIN doctos_sugerido_obra d ON d.docto_sugerido_obra_id = p.docto_sugerido_obra_id
 CROSS JOIN LATERAL jsonb_array_elements(coalesce(nullif(trim(d.analisis_pu), '')::jsonb->'conceptos', '[]'::jsonb)) WITH ORDINALITY AS o(c, n)
 CROSS JOIN LATERAL jsonb_array_elements(coalesce(o.c->'insumos', '[]'::jsonb)) WITH ORDINALITY AS o2(i, n2)
 WHERE o.n = p.orden
   AND NOT EXISTS (SELECT 1 FROM presupuesto_concepto_insumos x WHERE x.presupuesto_concepto_id = p.presupuesto_concepto_id);

