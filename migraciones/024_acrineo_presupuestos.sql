/****  Módulo propio de presupuestos y control de costos. Esta etapa crea  ****/
/****  el encabezado del presupuesto (ventana «Detalle del presupuesto»)   ****/
/****  repartido por tema en tablas pequeñas, sus documentos y su          ****/
/****  historial de cambios.                                               ****/
/****                                                                       ****/
/****  Reutiliza los catálogos que ya existen:                             ****/
/****    ciudades (016) · clientes (016) · zonas_clientes (016, Región)    ****/
/****    vendedores_obras · usuarios (Responsable)                         ****/
/****    plantillas_presupuesto (008, Contenido)                           ****/
/****  Solo agrega acrineo_empresas, que no existía.                       ****/
/****                                                                       ****/
/****  No modifica ni borra nada existente. Requiere 008 y 016.            ****/
/****  Se aplica con: php herramientas/migrar.php --aplicar                 ****/
