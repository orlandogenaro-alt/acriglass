/* ---------- Empresas que presentan el presupuesto ---------- */
CREATE TABLE IF NOT EXISTS acrineo_empresas (
    empresa_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(150) NOT NULL CHECK (btrim(nombre) <> ''),
    rfc          VARCHAR(18),
    estatus      CHAR(1) NOT NULL DEFAULT 'A' CHECK (estatus IN ('A', 'B')),
    created_by   VARCHAR(50),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_acrineo_empresas_nombre ON acrineo_empresas (upper(btrim(nombre)));

/* ---------- Presupuesto (pestaña PRESUPUESTO + datos del catálogo) ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuestos (
    presupuesto_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(20) UNIQUE,                          /* ACN-000001, se asigna al crear */
    nombre          VARCHAR(150) NOT NULL CHECK (btrim(nombre) <> ''),
    descripcion     TEXT NOT NULL CHECK (btrim(descripcion) <> ''),
    direccion       VARCHAR(250),
    colonia         VARCHAR(120),
    codigo_postal   VARCHAR(10),
    ciudad_id       INTEGER REFERENCES ciudades (ciudad_id),
    estado          VARCHAR(60),
    telefono        VARCHAR(35),
    correo          VARCHAR(150),
    observaciones   TEXT,
    tipo            VARCHAR(40) NOT NULL DEFAULT '01_Propios',   /* agrupación del catálogo */
    agrupador       VARCHAR(60),
    organizacion    VARCHAR(150),
    propietario     VARCHAR(50),                                 /* login del dueño */
    estatus         VARCHAR(15) NOT NULL DEFAULT 'BORRADOR'
                    CHECK (estatus IN ('BORRADOR', 'EN_PROCESO', 'ENVIADO', 'APROBADO', 'RECHAZADO', 'CANCELADO')),
    sobrecosto_pct  NUMERIC(9,4)  NOT NULL DEFAULT 0,             /* los calculará la hoja del presupuesto (etapa 2) */
    costo_directo   NUMERIC(18,2) NOT NULL DEFAULT 0,
    precio_venta    NUMERIC(18,2) NOT NULL DEFAULT 0,
    version         INTEGER NOT NULL DEFAULT 1,                  /* evita pisar cambios de otro usuario */
    created_by      VARCHAR(50),
    updated_by      VARCHAR(50),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ                                  /* eliminado (no se borra el renglón) */
);
CREATE INDEX IF NOT EXISTS ix_acrineo_presupuestos_vivos  ON acrineo_presupuestos (updated_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_acrineo_presupuestos_tipo   ON acrineo_presupuestos (tipo, agrupador) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_acrineo_presupuestos_ciudad ON acrineo_presupuestos (ciudad_id);
CREATE INDEX IF NOT EXISTS ix_acrineo_presupuestos_prop   ON acrineo_presupuestos (upper(propietario));

/* ---------- GENERALES ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuesto_generales (
    presupuesto_id        INTEGER PRIMARY KEY REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    responsable_id        INTEGER REFERENCES usuarios (usuario_id),
    cargo_responsable     VARCHAR(100),
    empresa_id            INTEGER REFERENCES acrineo_empresas (empresa_id),
    cliente_id            INTEGER REFERENCES clientes (cliente_id),
    area_cliente          VARCHAR(100),
    departamento_cliente  VARCHAR(100),
    contacto_cliente      VARCHAR(150),
    vendedor_id           INTEGER REFERENCES vendedores_obras (vendedor_obra_id),
    region_id             INTEGER REFERENCES zonas_clientes (zona_cliente_id)
);
CREATE INDEX IF NOT EXISTS ix_acrineo_generales_cliente ON acrineo_presupuesto_generales (cliente_id);

/* ---------- LICITACIÓN ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuesto_licitacion (
    presupuesto_id       INTEGER PRIMARY KEY REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    fecha_licitacion     DATE,
    numero_licitacion    VARCHAR(60),
    lugar_celebracion    VARCHAR(200),
    numero_convocatoria  VARCHAR(60),
    tipo_licitacion      VARCHAR(60),
    fecha_publicacion    DATE,
    fecha_inicio         DATE,
    dias                 INTEGER CHECK (dias IS NULL OR dias BETWEEN 1 AND 36500),
    fecha_terminacion    DATE,                                   /* fecha_inicio + días (la calcula el sistema) */
    CHECK (fecha_terminacion IS NULL OR fecha_inicio IS NULL OR fecha_terminacion >= fecha_inicio)
);

/* ---------- C.H.: porcentajes de espera / reserva por elemento ---------- */
CREATE TABLE IF NOT EXISTS acrineo_ch_parametros (
    ch_parametro_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id   INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    tipo             VARCHAR(30) NOT NULL CHECK (tipo IN ('depreciacion', 'inversion', 'seguros', 'mantenimiento', 'combustible',
                                                         'lubricante', 'llantas', 'piezas_especiales', 'operacion', 'otras_fuentes')),
    espera           NUMERIC(9,4) NOT NULL DEFAULT 0 CHECK (espera  BETWEEN 0 AND 1000),
    reserva          NUMERIC(9,4) NOT NULL DEFAULT 0 CHECK (reserva BETWEEN 0 AND 1000),
    UNIQUE (presupuesto_id, tipo)
);

/* ---------- C.H.: factores de lubricante y combustible, indicadores ---------- */
CREATE TABLE IF NOT EXISTS acrineo_ch_factores (
    ch_factor_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id   INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    grupo            VARCHAR(15) NOT NULL CHECK (grupo IN ('lubricante', 'combustible', 'indicador')),
    clave            VARCHAR(30) NOT NULL,
    valor_numerico   NUMERIC(12,6),
    valor_texto      VARCHAR(30),
    UNIQUE (presupuesto_id, clave)
);

/* ---------- CÁLCULO ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuesto_calculo (
    presupuesto_id        INTEGER PRIMARY KEY REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    iva                   NUMERIC(6,2) NOT NULL DEFAULT 16 CHECK (iva BETWEEN 0 AND 100),
    decimales_costos      SMALLINT NOT NULL DEFAULT 2 CHECK (decimales_costos     BETWEEN 0 AND 6),
    decimales_cantidades  SMALLINT NOT NULL DEFAULT 4 CHECK (decimales_cantidades BETWEEN 0 AND 6),
    decimales_explosion   SMALLINT NOT NULL DEFAULT 8 CHECK (decimales_explosion  BETWEEN 0 AND 8)
);

/* ---------- OTROS: monedas ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuesto_monedas (
    moneda_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id  INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    numero          SMALLINT NOT NULL CHECK (numero IN (1, 2)),
    descripcion     VARCHAR(40) NOT NULL,
    remate          VARCHAR(10) NOT NULL,
    tipo_cambio     NUMERIC(12,6) NOT NULL DEFAULT 1 CHECK (tipo_cambio > 0),
    UNIQUE (presupuesto_id, numero)
);

/* ---------- OTROS: partidas y contenido ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuesto_configuracion (
    presupuesto_id          INTEGER PRIMARY KEY REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    separador_partidas      CHAR(1) NOT NULL DEFAULT '.',
    contenido_plantilla_id  INTEGER REFERENCES plantillas_presupuesto (plantilla_id)
);

/* ---------- DOCUMENTOS (Libro C.H. por presupuesto; FASAR y pie de indirectos por moneda) ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuesto_documentos (
    documento_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id   INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    tipo_documento   VARCHAR(20) NOT NULL CHECK (tipo_documento IN ('libro_ch', 'libro_fasar', 'libro_indirectos')),
    moneda           SMALLINT CHECK (moneda IN (1, 2)),
    nombre_original  VARCHAR(150) NOT NULL,
    ruta_archivo     VARCHAR(250) NOT NULL,                      /* nombre aleatorio, nunca el original */
    almacen          VARCHAR(10) NOT NULL DEFAULT 'storage' CHECK (almacen IN ('storage', 'local')),
    mime_type        VARCHAR(120) NOT NULL,
    tamano           BIGINT NOT NULL CHECK (tamano > 0),
    sha256           CHAR(64),
    uploaded_by      VARCHAR(50),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((tipo_documento = 'libro_ch' AND moneda IS NULL) OR (tipo_documento <> 'libro_ch' AND moneda IS NOT NULL))
);
/* Un archivo por lugar: subir otro reemplaza al anterior */
CREATE UNIQUE INDEX IF NOT EXISTS uq_acrineo_documentos_lugar
    ON acrineo_presupuesto_documentos (presupuesto_id, tipo_documento, coalesce(moneda, 0));

/* ---------- HISTORIAL ---------- */
CREATE TABLE IF NOT EXISTS acrineo_presupuesto_historial (
    historial_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id   INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    usuario          VARCHAR(50),
    accion           VARCHAR(30) NOT NULL,                       /* CREAR, MODIFICAR, ELIMINAR, DOCUMENTO… */
    campo            VARCHAR(120),
    valor_anterior   TEXT,
    valor_nuevo      TEXT,
    ip               VARCHAR(45),
    fecha            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_acrineo_historial ON acrineo_presupuesto_historial (presupuesto_id, fecha DESC);

