/******************************************************************************/
/****  025 - ACRINEO · Hoja del presupuesto (etapa 2)                        ****/
/****                                                                       ****/
/****  Partidas y subpartidas en árbol (padre_id), el catálogo de          ****/
/****  conceptos de cada presupuesto (código, descripción, unidad y costo  ****/
/****  directo unitario) y los renglones: qué concepto va en qué partida   ****/
/****  y con qué cantidad. Un mismo concepto puede ir en varias partidas;  ****/
/****  al borrar una partida se borran sus renglones, no el concepto.      ****/
/****                                                                       ****/
/****  Requiere la 024. Se aplica con: php herramientas/migrar.php --aplicar ****/
/******************************************************************************/

CREATE TABLE IF NOT EXISTS acrineo_partidas (
    partida_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id  INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    padre_id        INTEGER REFERENCES acrineo_partidas (partida_id) ON DELETE CASCADE,
    codigo          VARCHAR(30) NOT NULL CHECK (btrim(codigo) <> ''),
    descripcion     TEXT NOT NULL CHECK (btrim(descripcion) <> ''),
    orden           INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (padre_id IS NULL OR padre_id <> partida_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_acrineo_partidas_codigo ON acrineo_partidas (presupuesto_id, upper(codigo));
CREATE INDEX IF NOT EXISTS ix_acrineo_partidas_arbol ON acrineo_partidas (presupuesto_id, padre_id, orden);

CREATE TABLE IF NOT EXISTS acrineo_conceptos (
    concepto_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id  INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    codigo          VARCHAR(30) NOT NULL CHECK (btrim(codigo) <> ''),
    descripcion     TEXT NOT NULL CHECK (btrim(descripcion) <> ''),
    unidad          VARCHAR(20),
    costo           NUMERIC(18,6) NOT NULL DEFAULT 0 CHECK (costo >= 0),   /* costo directo unitario */
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_acrineo_conceptos_codigo ON acrineo_conceptos (presupuesto_id, upper(codigo));

CREATE TABLE IF NOT EXISTS acrineo_partida_conceptos (
    renglon_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_id   INTEGER NOT NULL REFERENCES acrineo_partidas (partida_id) ON DELETE CASCADE,
    concepto_id  INTEGER NOT NULL REFERENCES acrineo_conceptos (concepto_id),
    cantidad     NUMERIC(18,6) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    orden        INTEGER NOT NULL DEFAULT 0,
    UNIQUE (partida_id, concepto_id)
);
CREATE INDEX IF NOT EXISTS ix_acrineo_renglones_partida  ON acrineo_partida_conceptos (partida_id, orden);
CREATE INDEX IF NOT EXISTS ix_acrineo_renglones_concepto ON acrineo_partida_conceptos (concepto_id);

ALTER TABLE acrineo_partidas          ENABLE ROW LEVEL SECURITY;
ALTER TABLE acrineo_conceptos         ENABLE ROW LEVEL SECURITY;
ALTER TABLE acrineo_partida_conceptos ENABLE ROW LEVEL SECURITY;
