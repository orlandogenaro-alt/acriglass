/******************************************************************************/
/****  026 - ACRINEO · Matriz de precio unitario y P.A.                      ****/
/****                                                                       ****/
/****  acrineo_matriz: insumos de la matriz de cada concepto del            ****/
/****  presupuesto (por unidad del concepto). Puede salir del catálogo de   ****/
/****  insumos del sistema (insumo_id, migración 004) o capturarse libre.   ****/
/****  El costo de cada insumo se guarda en la matriz (el precio del         ****/
/****  presupuesto no cambia solo si cambia el catálogo; se actualiza a    ****/
/****  propósito). base: null = cantidad por unidad del concepto;           ****/
/****  pct_mo / pct_mat = la cantidad es un % de la mano de obra / de los    ****/
/****  materiales de la matriz (herramienta menor, equipo de seguridad…).   ****/
/****                                                                       ****/
/****  acrineo_conceptos: costo_origen ('matriz' cuando el costo directo    ****/
/****  sale de su matriz) y P.A. (precio alzado: el precio unitario se      ****/
/****  captura fijo y no sale de costo × sobrecosto).                       ****/
/****                                                                       ****/
/****  Requiere 004 y 025. Se aplica con: php herramientas/migrar.php --aplicar ****/
/******************************************************************************/

ALTER TABLE acrineo_conceptos ADD COLUMN IF NOT EXISTS costo_origen VARCHAR(8) NOT NULL DEFAULT 'directo'
    CHECK (costo_origen IN ('directo', 'matriz'));
ALTER TABLE acrineo_conceptos ADD COLUMN IF NOT EXISTS precio_alzado BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE acrineo_conceptos ADD COLUMN IF NOT EXISTS precio_fijo NUMERIC(18,6) CHECK (precio_fijo IS NULL OR precio_fijo >= 0);

CREATE TABLE IF NOT EXISTS acrineo_matriz (
    matriz_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concepto_id      INTEGER NOT NULL REFERENCES acrineo_conceptos (concepto_id) ON DELETE CASCADE,
    insumo_id        INTEGER REFERENCES insumos (insumo_id) ON DELETE SET NULL,
    tipo             CHAR(3) NOT NULL CHECK (tipo IN ('MAT', 'MO', 'EQ', 'HER', 'BAS', 'OTR')),
    codigo           VARCHAR(30),
    descripcion      VARCHAR(250) NOT NULL CHECK (btrim(descripcion) <> ''),
    unidad           VARCHAR(20),
    base             VARCHAR(8) CHECK (base IS NULL OR base IN ('pct_mo', 'pct_mat')),
    cantidad         NUMERIC(18,6) NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    desperdicio_pct  NUMERIC(7,4) NOT NULL DEFAULT 0 CHECK (desperdicio_pct >= 0 AND desperdicio_pct < 100),
    costo            NUMERIC(18,6) NOT NULL DEFAULT 0 CHECK (costo >= 0),
    orden            INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_acrineo_matriz ON acrineo_matriz (concepto_id, orden);
CREATE INDEX IF NOT EXISTS ix_acrineo_matriz_insumo ON acrineo_matriz (insumo_id);

ALTER TABLE acrineo_matriz ENABLE ROW LEVEL SECURITY;
