/****                                                                       ****/
/****  acrineo_tipos_insumo: tipos que se eligen con la lupa de la columna  ****/
/****  Tipo de la matriz de precio unitario. Los seis del sistema           ****/
/****  (sistema = true) no se borran ni cambian de clave: el cálculo usa MO  ****/
/****  y MAT para los renglones «% de M.O.» / «% de materiales» y el         ****/
/****  catálogo de insumos (migración 004) usa MAT, MO, EQ, HER y BAS.      ****/
/****  Los demás (subcontratos, viáticos…) los agrega el usuario.           ****/
/****                                                                       ****/
/****  acrineo_matriz.tipo deja de estar limitado a los seis del sistema;   ****/
/****  el servidor valida que el tipo exista en este catálogo.              ****/
/****                                                                       ****/
/****  Requiere 026. Se aplica con: php herramientas/migrar.php --aplicar   ****/
/******************************************************************************/

CREATE TABLE IF NOT EXISTS acrineo_tipos_insumo (
    tipo_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo         VARCHAR(3) NOT NULL CHECK (tipo ~ '^[A-Z0-9]{1,3}$'),
    descripcion  VARCHAR(60) NOT NULL DEFAULT '',
    sistema      BOOLEAN NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_acrineo_tipos_insumo ON acrineo_tipos_insumo (tipo);

INSERT INTO acrineo_tipos_insumo (tipo, descripcion, sistema) VALUES
    ('MAT', 'Materiales', true),
    ('MO',  'Mano de obra', true),
    ('EQ',  'Equipo y maquinaria', true),
    ('HER', 'Herramienta', true),
    ('BAS', 'Básicos', true),
    ('OTR', 'Otros', true)
ON CONFLICT (tipo) DO NOTHING;

ALTER TABLE acrineo_matriz DROP CONSTRAINT IF EXISTS acrineo_matriz_tipo_check;

ALTER TABLE acrineo_tipos_insumo ENABLE ROW LEVEL SECURITY;
