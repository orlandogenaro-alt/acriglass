/****************************************************************************************/
/****  034 · ACRINEO › facturas y folios de Easy-Glass ligados a un presupuesto:      ****/
/****        facturas y pedidos de Microsip y presupuestos de Easy-Glass que se       ****/
/****        buscan por la API de Easy-Glass (botón «Facturas y Easy-Glass» de la     ****/
/****        hoja). Se guarda una copia de los datos del folio al ligarlo.            ****/
/****************************************************************************************/

CREATE TABLE IF NOT EXISTS acrineo_presupuesto_ligados (
    ligado_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_id  INTEGER NOT NULL REFERENCES acrineo_presupuestos (presupuesto_id) ON DELETE CASCADE,
    origen          VARCHAR(20) NOT NULL
                    CHECK (origen IN ('Factura Microsip', 'Pedido Microsip', 'Easy-Glass')),
    folio           VARCHAR(30) NOT NULL,
    folio_easy      VARCHAR(30),                 /* EG0000123 de la factura, si viene de un presupuesto de Easy-Glass */
    cliente         VARCHAR(200),
    detalle         VARCHAR(250),
    fecha           DATE,
    total           NUMERIC(18,2) NOT NULL DEFAULT 0,
    moneda          VARCHAR(10),
    estatus         VARCHAR(30),
    created_by      VARCHAR(50),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (presupuesto_id, origen, folio)
);
CREATE INDEX IF NOT EXISTS ix_acrineo_ligados_folio ON acrineo_presupuesto_ligados (upper(folio));
