/* ---------- Proveedores ---------- */
CREATE TABLE IF NOT EXISTS acrineo_proveedores (
    proveedor_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor      VARCHAR(20) NOT NULL CHECK (btrim(proveedor) <> ''),
    razon_social   VARCHAR(150) NOT NULL CHECK (btrim(razon_social) <> ''),
    ciudad_id      INTEGER REFERENCES ciudades (ciudad_id),
    rfc            VARCHAR(18),
    direccion      VARCHAR(200),
    colonia        VARCHAR(100),
    codigo_postal  VARCHAR(10),
    telefono       VARCHAR(35),
    fax            VARCHAR(35),
    mail           VARCHAR(150),
    contacto       VARCHAR(150),
    observaciones  VARCHAR(500),
    celular        VARCHAR(35),
    pagina_web     VARCHAR(200),
    es_default     BOOLEAN NOT NULL DEFAULT false,
    created_by     VARCHAR(50),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_acrineo_proveedores_clave ON acrineo_proveedores (upper(btrim(proveedor)));
CREATE INDEX IF NOT EXISTS ix_acrineo_proveedores_razon ON acrineo_proveedores (upper(btrim(razon_social)));

INSERT INTO acrineo_proveedores (proveedor, razon_social, created_by)
SELECT 'P' || lpad((row_number() OVER (ORDER BY n))::text, 4, '0'), n, 'migracion 035'
  FROM (SELECT DISTINCT ON (upper(btrim(proveedor))) btrim(proveedor) AS n
          FROM insumo_precios
         WHERE btrim(coalesce(proveedor, '')) <> ''
         ORDER BY upper(btrim(proveedor)), btrim(proveedor)) x
 WHERE NOT EXISTS (SELECT 1 FROM acrineo_proveedores)
   AND char_length(n) <= 150;

