/* ---------- Familias de insumos y conceptos ---------- */
CREATE TABLE IF NOT EXISTS acrineo_familias (
    familia_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    familia      VARCHAR(80) NOT NULL CHECK (btrim(familia) <> ''),
    descripcion  VARCHAR(150)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_acrineo_familias ON acrineo_familias (upper(btrim(familia)));

INSERT INTO acrineo_familias (familia, descripcion)
SELECT DISTINCT ON (upper(btrim(f))) btrim(f), btrim(f)
  FROM (SELECT familia AS f FROM insumos UNION ALL SELECT familia FROM conceptos_pu) x
 WHERE btrim(coalesce(f, '')) <> ''
 ORDER BY upper(btrim(f)), btrim(f)
ON CONFLICT DO NOTHING;

